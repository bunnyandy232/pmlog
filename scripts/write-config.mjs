/** Generate prototypes/config.js from .env.local */
import { readFileSync, writeFileSync, existsSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function loadEnv() {
  const env = { ...process.env };
  for (const file of [resolve(root, ".env.local"), resolve(root, ".env")]) {
    if (!existsSync(file)) continue;
    readFileSync(file, "utf8").split(/\r?\n/).forEach((line) => {
      const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/);
      if (!m) return;
      let v = m[2].trim();
      if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) {
        v = v.slice(1, -1);
      }
      if (!env[m[1]]) env[m[1]] = v;
    });
  }
  return env;
}

const env = loadEnv();
const url = env.SUPABASE_URL || "https://kiuhfbaqvgpojgxakvpl.supabase.co";
const anon = env.SUPABASE_ANON_KEY || "";
if (!anon) {
  console.error("SUPABASE_ANON_KEY missing in .env.local");
  process.exit(1);
}

const out = `/* auto-generated by scripts/write-config.mjs — do not commit */
window.PMLOG_CONFIG = {
  supabaseUrl: ${JSON.stringify(url)},
  supabaseAnonKey: ${JSON.stringify(anon)}
};
`;
writeFileSync(resolve(root, "prototypes/config.js"), out, "utf8");
console.log("Wrote prototypes/config.js");
